def square(side):
    # Площадь квадрата равна стороне, возведенной в квадрат
    return side * side  # или side ** 2

# Пример использования (вызов функции)
side_length = 5  # Вы можете выбрать любую длину стороны
area = square(side_length)

print(f"Площадь квадрата со стороной {side_length}: {area}")